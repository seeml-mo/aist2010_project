#!/usr/bin/env python3
"""Model-free chart generator.

Pipeline:
  audio -> multi-band superflux -> onsets -> beat grid -> timbre groups
        -> note selection -> holds -> chart JSON

The output contains chart data only. Terrain, gaps, enemies, camera and
spawn positions are generated by Godot from this chart.

Lane mapping:
  0 = attack
  1 = defend
  2 = jump

Timbre grouping is algorithmic, not learned:
  - jump   : percussive low band (kick / bass impact)
  - attack : percussive mid + high band (snare / clap / hats)

  - defend : harmonic mid + high band (vocal / melody / pads)

A note is a tap unless it has a positive "duration" (seconds).
"""
from __future__ import annotations

import argparse
from bisect import bisect_left
import json
import subprocess
import sys
from pathlib import Path

import numpy as np
from scipy import ndimage, signal

SR = 22050
HOP = 220
N_FFT = 2048
N_MELS = 64
LANE_NAMES = ["attack", "defend", "jump"]


def load_audio(path: Path, ffmpeg: str) -> np.ndarray:
    cmd = [ffmpeg, "-v", "error", "-i", str(path), "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"]
    raw = subprocess.check_output(cmd)
    audio = np.frombuffer(raw, dtype=np.float32).copy()
    peak = float(np.max(np.abs(audio))) if audio.size else 0.0
    if peak > 0:
        audio /= peak
    return audio


def mel_filterbank(sr: int, n_fft: int, n_mels: int = N_MELS, f_min: float = 20.0, f_max: float | None = None):
    if f_max is None:
        f_max = sr / 2.0

    def hz_to_mel(hz):
        return 2595.0 * np.log10(1.0 + hz / 700.0)

    def mel_to_hz(mel):
        return 700.0 * (10.0 ** (mel / 2595.0) - 1.0)

    mel_points = np.linspace(hz_to_mel(f_min), hz_to_mel(f_max), n_mels + 2)
    hz_points = mel_to_hz(mel_points)
    freqs = np.arange(n_fft // 2 + 1) * sr / n_fft
    filters = np.zeros((n_mels, freqs.size), dtype=np.float64)

    for i in range(n_mels):
        left, center, right = hz_points[i], hz_points[i + 1], hz_points[i + 2]
        up = (freqs - left) / max(center - left, 1e-9)
        down = (right - freqs) / max(right - center, 1e-9)
        filters[i] = np.maximum(0.0, np.minimum(up, down))

    centers = 0.5 * (hz_points[1:-1] + hz_points[2:])
    return filters, freqs, centers


def normalise(x: np.ndarray, percentile: float = 95.0) -> np.ndarray:
    scale = float(np.percentile(x, percentile))
    if scale <= 1e-9:
        return np.zeros_like(x)
    return np.clip(x / scale, 0.0, 1.0)


def analyse_audio(audio: np.ndarray, bpm_min: float, bpm_max: float):
    f, times, spectrum = signal.stft(
        audio, SR, nperseg=N_FFT, noverlap=N_FFT - HOP, boundary=None, padded=False
    )
    mag = np.abs(spectrum)
    filters, freqs, mel_centers = mel_filterbank(SR, N_FFT)

    mel = filters @ mag
    logmel = np.log1p(1000.0 * mel)
    # SuperFlux: max-filter along frequency suppresses vibrato / pitch drift.
    logmax = ndimage.maximum_filter1d(logmel, size=3, axis=0)
    flux = np.maximum(0.0, logmax[:, 1:] - logmel[:, :-1])
    flux = np.pad(flux, ((0, 0), (1, 0)), mode="constant")

    low_mask = (mel_centers >= 20) & (mel_centers < 150)
    mid_mask = (mel_centers >= 150) & (mel_centers < 2000)
    high_mask = (mel_centers >= 2000) & (mel_centers <= 9000)

    flux_low = normalise(flux[low_mask].sum(axis=0))
    flux_mid = normalise(flux[mid_mask].sum(axis=0))
    flux_high = normalise(flux[high_mask].sum(axis=0))

    onset = 0.50 * flux_low + 0.30 * flux_mid + 0.20 * flux_high
    onset = ndimage.gaussian_filter1d(onset, sigma=1.2)
    onset = normalise(onset)

    threshold = ndimage.median_filter(onset, size=31) + 0.02
    distance = max(1, int(round(0.05 / (HOP / SR))))
    peaks, props = signal.find_peaks(
        onset, height=threshold, distance=distance, prominence=0.02
    )
    if peaks.size < 24:
        peaks, props = signal.find_peaks(
            onset, height=threshold, distance=distance, prominence=0.01
        )

    peak_strength = normalise(onset[peaks]) if peaks.size else np.zeros(0)

    return {
        "times": times,
        "mag": mag,
        "freqs": freqs,
        "filters": filters,
        "mel": mel,
        "flux_low": flux_low,
        "flux_mid": flux_mid,
        "flux_high": flux_high,
        "onset": onset,
        "peaks": peaks,
        "peak_strength": peak_strength,
        "duration": len(audio) / SR,
    }


def track_beats(analysis: dict, bpm_min: float, bpm_max: float):
    onset = analysis["onset"]
    times = analysis["times"]
    dt = HOP / SR

    x = onset - onset.mean()
    ac = signal.correlate(x, x, mode="full", method="fft")[x.size - 1:]
    lag_min = max(1, int(round(60.0 / bpm_max / dt)))
    lag_max = min(ac.size - 1, int(round(60.0 / bpm_min / dt)))
    if lag_max <= lag_min:
        lag_min, lag_max = max(1, lag_max - 10), lag_max

    lags = np.arange(lag_min, lag_max + 1)
    bpms = 60.0 / (lags * dt)
    tempo_prior = np.exp(-0.5 * ((bpms - 120.0) / 35.0) ** 2)
    period = float(lags[np.argmax(ac[lags] * tempo_prior)] * dt)

    # Refine period and phase on the onset envelope itself.
    best_score, best_period, best_phase = -1.0, period, 0.0
    for candidate in np.arange(period * 0.94, period * 1.06, dt / 8.0):
        if candidate <= 0:
            continue
        for phase in np.arange(0.0, candidate, dt):
            beat_times = np.arange(phase, times[-1], candidate)
            if beat_times.size < 4:
                continue
            score = float(np.interp(beat_times, times, onset).mean())
            if score > best_score:
                best_score, best_period, best_phase = score, float(candidate), float(phase)

    beats = np.arange(best_phase, times[-1], best_period)
    beats = beats[(beats >= 0) & (beats < analysis["duration"])]

    # Local refinement: snap each beat to the nearest onset peak within 35 ms.
    refined = []
    for beat in beats:
        lo = int(np.searchsorted(times, beat - 0.035))
        hi = int(np.searchsorted(times, beat + 0.035))
        if hi > lo:
            local = onset[lo:hi]
            idx = lo + int(np.argmax(local))
            if local.size and local.max() > 0.08:
                refined.append(float(times[idx]))
                continue
        refined.append(float(beat))

    return 60.0 / best_period, np.asarray(refined, dtype=np.float64)


def find_downbeats(beats: np.ndarray, analysis: dict) -> np.ndarray:
    if beats.size < 4:
        return beats.copy()

    times = analysis["times"]
    low = analysis["flux_low"]
    novelty = analysis["onset"]
    low_at_beats = np.interp(beats, times, low)
    novelty_at_beats = np.interp(beats, times, novelty)

    best_phase, best_score = 0, -1.0
    for phase in range(4):
        idx = np.arange(phase, beats.size, 4)
        score = float(low_at_beats[idx].sum() + 0.5 * novelty_at_beats[idx].sum())
        if score > best_score:
            best_phase, best_score = phase, score

    return beats[best_phase::4]


def timbre_envelopes(analysis: dict) -> list[np.ndarray]:
    """Return smoothed attack/defend/jump envelopes from HPSS band energy."""
    mag = analysis["mag"]
    filters = analysis["filters"]
    _, _, centers = mel_filterbank(SR, N_FFT)
    low_mask = (centers >= 20) & (centers < 150)
    mid_mask = (centers >= 150) & (centers < 2000)
    high_mask = (centers >= 2000) & (centers <= 9000)

    # Harmonic / percussive separation with median filters (no training).
    harmonic = ndimage.median_filter(mag, size=(1, 31))
    percussive = ndimage.median_filter(mag, size=(31, 1))
    denom = harmonic + percussive + 1e-9
    harmonic = mag * (harmonic / denom)
    percussive = mag * (percussive / denom)

    perc_mel = filters @ percussive

    env_jump = perc_mel[low_mask].sum(axis=0)
    env_attack = perc_mel[mid_mask].sum(axis=0) + perc_mel[high_mask].sum(axis=0)
    env_defend = (filters @ harmonic)[mid_mask | high_mask].sum(axis=0)
    envelopes = [normalise(env_attack), normalise(env_defend), normalise(env_jump)]
    return [ndimage.gaussian_filter1d(env, sigma=2.0) for env in envelopes]


def band_candidates(analysis: dict, envelopes: list[np.ndarray]) -> list[dict]:
    """Detect onsets independently in each lane's own timbre envelope.

    This is the direct fix for weak lower lanes: a note only exists when that
    lane's band actually has a local peak, instead of classifying a global
    onset that may have little energy in that band.
    """
    times = analysis["times"]
    global_peaks = analysis["peaks"]
    global_times = times[global_peaks] if global_peaks.size else np.zeros(0)
    candidates: list[dict] = []
    # attack, defend, jump
    distances = (8, 12, 15)
    thresholds = (0.025, 0.030, 0.030)

    for lane, env in enumerate(envelopes):
        if env.size == 0:
            continue
        threshold = ndimage.median_filter(env, size=31) + thresholds[lane]
        peaks, _ = signal.find_peaks(
            env,
            height=threshold,
            distance=distances[lane],
            prominence=0.02,
        )
        if peaks.size == 0:
            continue

        strengths = env[peaks]
        scale = float(np.percentile(strengths, 95)) + 1e-9
        for peak, strength in zip(peaks, strengths):
            value = float(np.clip(strength / scale, 0.0, 1.0))
            if value < 0.12:
                continue

            # Smoothed timbre envelopes have broad peaks. Snap to the nearest
            # global onset for percussive lanes. Keep harmonic peaks at their own time.
            frame = int(peak)
            note_time = float(times[peak])
            if lane != 1 and global_times.size:
                index = int(np.searchsorted(global_times, note_time))
                nearby = []
                if index < global_times.size:
                    nearby.append(index)
                if index > 0:
                    nearby.append(index - 1)
                if nearby:
                    best = min(nearby, key=lambda j: abs(float(global_times[j]) - note_time))
                    if abs(float(global_times[best]) - note_time) <= 0.06:
                        frame = int(global_peaks[best])
                        note_time = float(global_times[best])

            candidates.append(
                {
                    "time": note_time,
                    "frame": frame,
                    "lane": lane,
                    "confidence": value,
                    "score": value,
                    "source": "band",
                }
            )

    return candidates


def select_candidates(
    candidates: list[dict],
    duration: float,
    difficulty: str,
    beats: np.ndarray,
    downbeats: np.ndarray,
) -> list[dict]:
    settings = {
        # global minimum gap, same-lane minimum gap, target notes per second, maximum notes per 2 seconds
        "easy": (0.550, 0.700, 0.9, 3),
        "normal": (0.420, 0.550, 1.3, 4),
        "hard": (0.260, 0.360, 2.0, 4),
    }
    min_gap, lane_gap, target_nps, max_per_2s = settings[difficulty]
    # Jump airtime is ~0.47 s. Keep extra recovery time so two jump
    # events must be at least 0.9 s apart to remain physically playable.
    lane_gaps = [lane_gap, lane_gap, max(0.9, lane_gap)]
    max_notes = max(1, int(round(duration * target_nps)))

    half_beats = (beats[:-1] + beats[1:]) * 0.5
    beat_grid = np.sort(np.concatenate((beats, half_beats)))
    downbeats = np.sort(downbeats)

    def proximity(note_time: float, grid: np.ndarray, tolerance: float) -> float:
        if grid.size == 0:
            return 0.0
        index = int(np.searchsorted(grid, note_time))
        nearest = grid[max(0, index - 1):index + 1]
        distance = float(np.min(np.abs(nearest - note_time)))
        return max(0.0, 1.0 - distance / tolerance)

    def selection_score(candidate: dict) -> float:
        note_time = candidate["time"]
        return (
            candidate["score"]
            + 0.20 * proximity(note_time, beat_grid, 0.08)
            + 0.10 * proximity(note_time, downbeats, 0.08)
        )

    selected: list[dict] = []
    selected_times: list[float] = []
    for candidate in sorted(candidates, key=selection_score, reverse=True):
        if len(selected) >= max_notes:
            break
        # Leave a short lead-in for the player to settle, and keep jump gaps
        # away from the very start/end of the track.
        if candidate["time"] < 1.0:
            continue
        if candidate["lane"] == 2 and (
            candidate["time"] < 2.0 or candidate["time"] > duration - 1.5
        ):
            continue
        if any(abs(candidate["time"] - other["time"]) < min_gap for other in selected):
            continue
        if any(
            candidate["lane"] == other["lane"]
            and abs(candidate["time"] - other["time"]) < lane_gaps[candidate["lane"]]
            for other in selected
        ):
            continue
        note_time = candidate["time"]
        index = bisect_left(selected_times, note_time)
        # Any newly overcrowded window must include the inserted note.
        # Before insertion, its other notes form a run of max_per_2s entries.
        first = max(0, index - max_per_2s)
        last = min(index, len(selected_times) - max_per_2s)
        if any(
            max(note_time, selected_times[start + max_per_2s - 1])
            - min(note_time, selected_times[start]) < 2.0
            for start in range(first, last + 1)
        ):
            continue
        selected_times.insert(index, note_time)
        selected.insert(index, candidate)

    return selected


def detect_holds(notes: list[dict], envelopes: list[np.ndarray], duration: float) -> None:
    """Mark a note as a hold only when the lane's energy actually sustains.

    Percussive hits (kick/snare/hat) decay quickly and therefore stay taps.
    Only the attack lane supports holds.
    """
    dt = HOP / SR
    early_frames = (2, 8)     # ~20-70 ms after the onset
    late_frames = (15, 30)    # ~150-300 ms after the onset

    hold_candidates: list[tuple[float, dict, float]] = []

    lane_notes = [note for note in notes if note["lane"] == 0]
    env = envelopes[0]
    sustain_min, late_min, max_hold = 0.95, 0.45, 0.6
    for i, note in enumerate(lane_notes):
        peak = note["frame"]
        if peak >= env.size:
            continue
        reference = float(env[peak])
        if reference < 0.25 or peak + late_frames[0] >= env.size:
            continue

        early_slice = env[peak + early_frames[0]: min(env.size, peak + early_frames[1])]
        late_slice = env[peak + late_frames[0]: min(env.size, peak + late_frames[1])]
        if early_slice.size == 0 or late_slice.size == 0:
            continue

        early = float(early_slice.mean())
        late = float(late_slice.mean())
        sustain = late / (early + 1e-9)
        if sustain < sustain_min or late < late_min:
            continue

        gap = duration - note["time"]
        if i + 1 < len(lane_notes):
            gap = lane_notes[i + 1]["time"] - note["time"]
        if gap < 0.80:
            continue

        target = min(0.50 * gap, max_hold)
        end_limit = min(env.size - 1, peak + int(target / dt))
        end = peak
        while end < end_limit and env[end] > 0.35 * reference:
            end += 1

        hold = (end - peak) * dt
        if 0.30 <= hold <= max_hold:
            hold_candidates.append((sustain * late, note, hold))

    # Keep the ratio of holds comparable across difficulties.
    max_holds = max(2, int(round(len(notes) * 0.15)))
    for _, note, hold in sorted(hold_candidates, key=lambda item: item[0], reverse=True)[:max_holds]:
        note["duration"] = round(float(hold), 3)


def publish_notes(notes: list[dict]) -> list[dict]:
    published = []
    for note in notes:
        item = {"time": round(float(note["time"]), 5), "lane": int(note["lane"])}
        if "duration" in note:
            item["duration"] = round(float(note["duration"]), 3)
        published.append(item)
    return published


def build_chart(args) -> dict:
    audio = load_audio(args.audio, args.ffmpeg)
    analysis = analyse_audio(audio, args.bpm_min, args.bpm_max)
    bpm, beats = track_beats(analysis, args.bpm_min, args.bpm_max)
    downbeats = find_downbeats(beats, analysis)
    envelopes = timbre_envelopes(analysis)
    candidates = band_candidates(analysis, envelopes)
    notes = select_candidates(candidates, analysis["duration"], args.difficulty, beats, downbeats)
    detect_holds(notes, envelopes, analysis["duration"])

    chart = {
        "version": 2,
        "audio": {
            "stream": args.stream or f"res://assets/{Path(args.audio).name}",
            "title": args.title,
            "artist": args.artist,
            "license": args.license,
            "duration": round(float(analysis["duration"]), 3),
            "offset": 0.0,
        },
        "timing": {
            "bpm": round(float(bpm), 3),
            "beats": [round(float(t), 5) for t in beats],
            "downbeats": [round(float(t), 5) for t in downbeats],
        },
        "chart": {
            "lanes": LANE_NAMES,
            "notes": publish_notes(notes),
        },
    }

    counts = (
        np.bincount([note["lane"] for note in notes], minlength=len(LANE_NAMES))
        if notes
        else np.zeros(len(LANE_NAMES), dtype=int)
    )
    holds = sum(1 for note in notes if "duration" in note)
    print(
        f"bpm={bpm:.2f} beats={len(beats)} onsets={analysis['peaks'].size} "
        f"notes={len(notes)} holds={holds} "
        f"lanes(attack/defend/jump)={counts.tolist()}"
    )
    return chart


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate a band-gated 3-lane chart JSON.")
    parser.add_argument("--audio", type=Path, default=Path("assets/voxel_30s.ogg"))
    parser.add_argument("--ffmpeg", default="ffmpeg")
    parser.add_argument("--output", type=Path, default=Path("assets/maps/chart_band.json"))
    parser.add_argument("--stream", default=None, help="Audio resource path written into the chart.")
    parser.add_argument("--title", default="Voxel Revolution")
    parser.add_argument("--artist", default="Kevin MacLeod")
    parser.add_argument("--license", default="CC BY 4.0")
    parser.add_argument("--difficulty", choices=["easy", "normal", "hard"], default="normal")
    parser.add_argument("--bpm-min", type=float, default=80.0)
    parser.add_argument("--bpm-max", type=float, default=180.0)
    args = parser.parse_args()

    if not args.audio.exists():
        parser.error(f"audio file not found: {args.audio}")

    chart = build_chart(args)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(chart, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
