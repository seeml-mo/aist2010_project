#!/usr/bin/env python3
"""Timbre-grouped chart generator.

Pipeline (project proposal, sections 1-4):

  audio -> descriptors -> GMM soft timbre grouping -> per-group smoothing
        -> o_g(t) = q_g(t) * SF(t) -> adaptive per-group onset picking
        -> playability selection -> lanes -> optional holds -> chart JSON

Groups are unsupervised. Their names ("attack", "defend", "jump") are
assigned afterwards from measured character (centroid, percussive share),
and can be overridden with --map when the automatic choice is not musical.

The output is chart version 2 only: audio metadata, timing and notes.
Terrain, scenery and targets are generated by Godot, so the game scene does
not need to change when the analysis changes.
"""
from __future__ import annotations

import argparse
import json
import sys
from bisect import bisect_left
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))

import audio_features as features_lib  # noqa: E402
import beat_tracker  # noqa: E402
import timbre_export  # noqa: E402
import timbre_grouping  # noqa: E402

LANE_NAMES = ["attack", "defend", "jump"]
JUMP_LANE = 2
HOP_SECONDS = features_lib.HOP / features_lib.SR
METHOD = (
    "MFCC + flatness/RMS/attack/flux descriptors, diagonal GMM soft grouping, "
    "per-group Gaussian smoothing, o_g=q_g*SF onset envelopes, adaptive per-group "
    "peak picking, minimum spacing, playability filter. Global beats from "
    "spectral-flux autocorrelation tempo plus DP tracking."
)


def parse_lane_override(text: str | None) -> dict[int, int]:
    """Parse "0:1,1:0,2:2" into {group: lane}."""
    if not text:
        return {}
    mapping: dict[int, int] = {}
    for item in text.split(","):
        item = item.strip()
        if not item:
            continue
        group_text, lane_text = item.split(":")
        group, lane = int(group_text), int(lane_text)
        if not 0 <= lane < len(LANE_NAMES):
            raise ValueError(f"lane out of range: {lane}")
        mapping[group] = lane
    return mapping


def select_notes(candidates: list[dict], duration: float, difficulty: str,
                 beats: np.ndarray, downbeats: np.ndarray) -> list[dict]:
    """Keep the musically strongest candidates that stay playable."""
    settings = {
        # global gap, same lane gap, target notes per second, max in any 2 s
        "easy": (0.550, 0.700, 0.9, 3),
        "normal": (0.420, 0.550, 1.3, 4),
        "hard": (0.260, 0.360, 2.0, 4),
    }
    min_gap, lane_gap, target_nps, max_per_2s = settings[difficulty]
    # Jump airtime is ~0.47 s, so consecutive jumps need real recovery time.
    lane_gaps = [lane_gap, lane_gap, max(0.9, lane_gap)]
    max_notes = max(1, int(round(duration * target_nps)))

    half_beats = (beats[:-1] + beats[1:]) * 0.5 if beats.size > 1 else beats
    beat_grid = np.sort(np.concatenate((beats, half_beats)))
    downbeats = np.sort(downbeats)

    def proximity(note_time: float, grid: np.ndarray, tolerance: float) -> float:
        if grid.size == 0:
            return 0.0
        index = int(np.searchsorted(grid, note_time))
        nearest = grid[max(0, index - 1):index + 1]
        return max(0.0, 1.0 - float(np.min(np.abs(nearest - note_time))) / tolerance)

    def score(candidate: dict) -> float:
        return (
            candidate["strength"]
            + 0.20 * proximity(candidate["time"], beat_grid, 0.08)
            + 0.10 * proximity(candidate["time"], downbeats, 0.08)
        )

    selected: list[dict] = []
    selected_times: list[float] = []
    for candidate in sorted(candidates, key=score, reverse=True):
        if len(selected) >= max_notes:
            break
        note_time = candidate["time"]
        # Lead-in so the player can settle; keep jumps clear of both edges.
        if note_time < 1.0:
            continue
        if candidate["lane"] == JUMP_LANE and (note_time < 2.0 or note_time > duration - 1.5):
            continue
        if any(abs(note_time - other["time"]) < min_gap for other in selected):
            continue
        if any(
            candidate["lane"] == other["lane"]
            and abs(note_time - other["time"]) < lane_gaps[candidate["lane"]]
            for other in selected
        ):
            continue

        index = bisect_left(selected_times, note_time)
        first = max(0, index - max_per_2s)
        last = min(index, len(selected_times) - max_per_2s)
        overcrowded = any(
            max(note_time, selected_times[start + max_per_2s - 1])
            - min(note_time, selected_times[start]) < 2.0
            for start in range(first, last + 1)
        )
        if overcrowded:
            continue

        selected_times.insert(index, note_time)
        selected.insert(index, candidate)

    return selected


def detect_holds(notes: list[dict], envelope: np.ndarray, lane: int,
                 duration: float) -> None:
    """Mark notes as holds where the timbre layer actually sustains.

    Only applied to the tonal lane: percussive hits decay too quickly and a
    hold on a drum would be unplayable.
    """
    lane_notes = [note for note in notes if note["lane"] == lane]
    if not lane_notes:
        return

    early = slice(2, 8)        # ~45-185 ms after the onset
    late = slice(15, 30)       # ~350-700 ms after the onset
    candidates: list[tuple[float, dict, float]] = []

    for index, note in enumerate(lane_notes):
        peak = note["frame"]
        if peak >= envelope.size or peak + late.start >= envelope.size:
            continue
        reference = float(envelope[peak])
        if reference < 0.25:
            continue

        early_slice = envelope[peak + early.start: min(envelope.size, peak + early.stop)]
        late_slice = envelope[peak + late.start: min(envelope.size, peak + late.stop)]
        if early_slice.size == 0 or late_slice.size == 0:
            continue

        sustain = float(late_slice.mean()) / (float(early_slice.mean()) + 1e-9)
        if sustain < 0.85 or float(late_slice.mean()) < 0.45:
            continue

        gap = duration - note["time"]
        if index + 1 < len(lane_notes):
            gap = lane_notes[index + 1]["time"] - note["time"]
        if gap < 0.80:
            continue

        target = min(0.50 * gap, 0.6)
        limit = min(envelope.size - 1, peak + int(target / HOP_SECONDS))
        end = peak
        while end < limit and envelope[end] > 0.5 * reference:
            end += 1

        length = (end - peak) * HOP_SECONDS
        if 0.30 <= length <= 0.6:
            candidates.append((sustain, note, length))

    limit = max(2, int(round(len(notes) * 0.15)))
    for _, note, length in sorted(candidates, key=lambda item: item[0], reverse=True)[:limit]:
        note["duration"] = round(float(length), 3)


def analyse(args) -> dict:
    """Run the analysis once; shared by the chart and the timbre export."""
    audio_path = Path(args.audio)
    features = features_lib.extract(audio_path)
    matrix = features_lib.whiten(features_lib.grouping_matrix(features), args.components)

    hop = float(features.times[1] - features.times[0])
    bpm, beat_frames = beat_tracker.track_beats(
        features.flux, hop, args.bpm_min, args.bpm_max
    )
    beats = beat_tracker.beats_to_times(beat_frames, features.times)
    downbeats = beat_tracker.beats_to_times(
        beat_tracker.find_downbeats(beat_frames, features.bands[:, 0],
                                    features.flux, features.times),
        features.times,
    )

    model = timbre_grouping.fit_groups(matrix, groups=args.groups, seed=args.seed)
    descriptions = timbre_grouping.group_character(features, model)
    lane_map = timbre_grouping.assign_lanes(descriptions)
    lane_map.update(parse_lane_override(args.map))

    if args.mode == "pooled":
        candidates = timbre_grouping.detect_pooled(
            features, model, min_spacing=args.min_spacing, delta=args.delta
        )
    else:
        candidates = timbre_grouping.detect_grouped(
            features, model, sigma=args.sigma,
            min_spacing=args.min_spacing, delta=args.delta
        )
    for candidate in candidates:
        candidate["lane"] = int(lane_map.get(candidate["group"], JUMP_LANE))

    return {
        "audio_path": audio_path,
        "features": features,
        "model": model,
        "descriptions": descriptions,
        "lane_map": lane_map,
        "candidates": candidates,
        "bpm": bpm,
        "beats": beats,
        "downbeats": downbeats,
    }


def build_chart(args) -> dict:
    context = analyse(args)
    audio_path = context["audio_path"]
    features = context["features"]
    model = context["model"]
    descriptions = context["descriptions"]
    lane_map = context["lane_map"]
    candidates = context["candidates"]
    bpm = context["bpm"]
    beats = context["beats"]
    downbeats = context["downbeats"]

    notes = select_notes(candidates, features.duration, args.difficulty, beats, downbeats)

    hold_lane = 1
    hold_group = next((g for g, lane in lane_map.items() if lane == hold_lane), None)
    if not args.no_holds and hold_group is not None:
        sustain = timbre_grouping.sustain_envelope(
            features, descriptions[hold_group], args.sigma
        )
        detect_holds(notes, sustain, hold_lane, features.duration)

    chart = {
        "version": 2,
        "audio": {
            "stream": args.stream or f"res://assets/{audio_path.name}",
            "title": args.title,
            "artist": args.artist,
            "license": args.license,
            "duration": round(float(features.duration), 3),
            "offset": 0.0,
        },
        "timing": {
            "bpm": round(float(bpm), 3),
            "beats": [round(float(value), 5) for value in beats],
            "downbeats": [round(float(value), 5) for value in downbeats],
        },
        "chart": {
            "lanes": LANE_NAMES,
            "notes": [
                {
                    "time": round(float(note["time"]), 5),
                    "lane": int(note["lane"]),
                    **({"duration": round(float(note["duration"]), 3)}
                       if "duration" in note else {}),
                }
                for note in notes
            ],
        },
        "analysis": {
            "method": METHOD,
            "mode": args.mode,
            "difficulty": args.difficulty,
            "seed": args.seed,
            "parameters": {
                "groups": args.groups,
                "whitened_components": args.components,
                "smoothing_sigma_frames": args.sigma,
                "min_onset_spacing": args.min_spacing,
                "peak_delta": args.delta,
                "samplerate": features.samplerate,
                "frame": features_lib.N_FFT,
                "hop": features_lib.HOP,
                "bpm_range": [args.bpm_min, args.bpm_max],
            },
            "group_statistics": descriptions,
            "lane_map": {str(group): lane for group, lane in sorted(lane_map.items())},
            "candidates": len(candidates),
            "pooled_candidates": len(
                timbre_grouping.detect_pooled(features, model, min_spacing=args.min_spacing)
            ),
        },
    }
    if args.groups_json:
        document = timbre_export.build_document(
            features, model, descriptions, lane_map, bpm, beats, downbeats,
            candidates, notes,
            stream=chart["audio"]["stream"],
            title=args.title,
            method=METHOD,
        )
        timbre_export.write_document(Path(args.groups_json), document)
        print(f"wrote {args.groups_json} (timbre groups, {len(candidates)} events)")
    return chart


def summarise(chart: dict) -> None:
    notes = chart["chart"]["notes"]
    counts = np.bincount([note["lane"] for note in notes], minlength=len(LANE_NAMES)) \
        if notes else np.zeros(len(LANE_NAMES), dtype=int)
    holds = sum(1 for note in notes if "duration" in note)
    analysis = chart["analysis"]
    print(
        f"bpm={chart['timing']['bpm']:.2f} beats={len(chart['timing']['beats'])} "
        f"groups={analysis['parameters']['groups']} mode={analysis['mode']} "
        f"notes={len(notes)} holds={holds} "
        f"lanes(attack/defend/jump)={counts.tolist()} "
        f"candidates={analysis['candidates']}"
    )
    for description in analysis["group_statistics"]:
        lane = analysis["lane_map"].get(str(description["group"]), -1)
        print(
            "  group {g}: lane={lane} weight={w:.2f} centroid={c:.0f}Hz "
            "percussive={p:.2f} flatness={f:.3f}".format(
                g=description["group"],
                lane=LANE_NAMES[lane] if lane >= 0 else "unmapped",
                w=description["weight"],
                c=description["centroid"],
                p=description["percussive"],
                f=description["flatness"],
            )
        )


def stream_exists(stream: str) -> bool:
    """True when a res:// stream path resolves to a file inside the project."""
    if not stream.startswith("res://"):
        return True
    project_root = Path(__file__).resolve().parents[1]
    return (project_root / stream[len("res://"):]).exists()


def main() -> int:
    parser = argparse.ArgumentParser(description="Timbre-grouped chart generator (chart v2).")
    parser.add_argument("--audio", type=Path, default=Path("assets/voxel_30s.ogg"))
    parser.add_argument("--output", type=Path, default=Path("assets/maps/chart_timbre.json"))
    parser.add_argument("--groups-json", type=Path, default=None,
                        help="Also write the timbre-group document, e.g. "
                             "assets/analysis/voxel_30s_timbre.json")
    parser.add_argument("--stream", default=None, help="Audio resource path written into the chart.")
    parser.add_argument("--title", default="Voxel Revolution")
    parser.add_argument("--artist", default="Kevin MacLeod")
    parser.add_argument("--license", default="CC BY 4.0")
    parser.add_argument("--difficulty", choices=["easy", "normal", "hard"], default="normal")
    parser.add_argument("--mode", choices=["grouped", "pooled"], default="grouped",
                        help="pooled is the ablation baseline: one onset stream, labels by argmax.")
    parser.add_argument("--groups", type=int, default=3)
    parser.add_argument("--components", type=int, default=8,
                        help="Whitened dimensions the GMM clusters on.")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--sigma", type=float, default=1.5, help="Group smoothing, in frames.")
    parser.add_argument("--min-spacing", type=float, default=0.06, help="Seconds between onsets.")
    parser.add_argument("--delta", type=float, default=0.03, help="Adaptive peak threshold offset.")
    parser.add_argument("--map", default=None, help='Manual lane override, e.g. "0:1,1:2,2:0".')
    parser.add_argument("--no-holds", action="store_true")
    parser.add_argument("--bpm-min", type=float, default=80.0)
    parser.add_argument("--bpm-max", type=float, default=180.0)
    args = parser.parse_args()

    if not args.audio.exists():
        parser.error(f"audio file not found: {args.audio}")

    chart = build_chart(args)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(chart, indent=2) + "\n", encoding="utf-8")
    summarise(chart)
    print(f"wrote {args.output}")
    if not stream_exists(chart["audio"]["stream"]):
        print(
            f"WARNING: {chart['audio']['stream']} does not exist in the project.\n"
            f"         The song menu skips charts whose audio is missing, so this track\n"
            f"         will not appear. Re-run with --stream pointing at the real audio,\n"
            f"         or omit --stream (it defaults to the --audio file name)."
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
